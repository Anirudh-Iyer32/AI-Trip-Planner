def save_document(response_text: str, directory: str = "./output") -> str | None:
    """Export travel plan to markdown file with proper formatting"""
    os.makedirs(directory, exist_ok=True)

    markdown_content = f"""# AI Travel Plan
# **Generated:** {datetime.datetime.now().strftime('%Y-%m-%d at %H:%M')}  
# **Created by:** VOYAGE AI Travel Agent

---

{response_text}

---

*This travel plan was generated by AI. Please verify all information, especially prices, operating hours, and travel requirements before your trip.*
"""

    try:
        timestamp = datetime.datetime.now().strftime("%Y-%m-%d_%H-%M-%S")
        filename = f"{directory}/AI_Trip_Planner_{timestamp}.md"

        with open(filename, "w", encoding="utf-8") as f:
            f.write(markdown_content)

        print(f"Markdown file saved as: {filename}")
        return filename

    except Exception as e:
        print(f"Error saving markdown file: {e}")
        return None


def esc(text: str) -> str:
    """Escape XML characters for ReportLab Paragraphs"""
    if text is None:
        return ""
    return (
        str(text)
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )


def inline_md(txt: str) -> str:
    """Converts inline markdown formatting (bold, italic, code) to ReportLab XML tags."""
    txt = esc(txt)
    txt = re.sub(r"\*\*\*(.+?)\*\*\*", r"<b><i>\1</i></b>", txt)
    txt = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", txt)
    txt = re.sub(r"\*(.+?)\*", r"<i>\1</i>", txt)
    txt = re.sub(r"_(.+?)_", r"<i>\1</i>", txt)
    txt = re.sub(r"`(.+?)`", r"<font name='Courier'>\1</font>", txt)
    return txt


def parse_markdown_table_to_flowable(table_lines: List[str], base_styles, col_widths=None) -> Table | None:
    """Converts raw pipe-delimited markdown lines into a styled ReportLab Table flowable."""
    if len(table_lines) < 2:
        return None

    header_raw = table_lines[0].strip("|").split("|")
    headers = [h.strip() for h in header_raw]
    
    rows = []
    # Style for headers
    th_style = ParagraphStyle(
        "THStyle",
        parent=base_styles["Normal"],
        fontSize=9,
        leading=11,
        fontName="Helvetica-Bold",
        textColor=colors.HexColor("#FFFFFF")
    )
    td_style = ParagraphStyle(
        "TDStyle",
        parent=base_styles["Normal"],
        fontSize=8.5,
        leading=11,
        fontName="Helvetica",
        textColor=colors.HexColor("#2C2C2A")
    )

    header_row = [Paragraph(f"<b>{esc(h)}</b>", th_style) for h in headers]
    rows.append(header_row)

    # Skip separator (line 1)
    for line in table_lines[2:]:
        cols = [c.strip() for c in line.strip("|").split("|")]
        if not any(cols):
            continue
        padded = cols + [""] * (len(headers) - len(cols))
        row_flowables = [Paragraph(inline_md(c), td_style) for c in padded[:len(headers)]]
        rows.append(row_flowables)

    if len(rows) <= 1:
        return None

    # Calculate reasonable widths for A4 (usable width ~ 17cm = 480pt)
    usable_width = 480
    num_cols = len(headers)
    if not col_widths:
        w = usable_width / num_cols
        col_widths = [w] * num_cols

    t = Table(rows, colWidths=col_widths)
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#1A1A18")),
        ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.whitesmoke),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.HexColor("#FFFFFF"), colors.HexColor("#F9F7F2")]),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#E5DFC5")),
    ]))
    return t


